const reduced = matchMedia('(prefers-reduced-motion: reduce)');
const tiles = document.querySelectorAll('.bento-grid > .tile');

if (tiles.length) {
  const viewer = document.createElement('dialog');
  viewer.className = 'card-viewer';
  viewer.setAttribute('aria-labelledby', 'viewer-title');
  document.body.append(viewer);

  const prepared = new Map();
  const timing = {open: 600, close: 440, reveal: 320};
  const easing = 'cubic-bezier(.4,0,.2,1)';
  let origin, surface;
  let closing = false;
  let previousOverflow = '';
  let animations = [];
  let frame1 = 0, frame2 = 0;
  const cardRadius = () => innerWidth <= 580 ? '22px' : '28px';

  function prepare(tile) {
    const language = document.documentElement.lang;
    const saved = prepared.get(tile);
    if (saved?.language === language) return saved.content;
    const content = document.createElement('article');
    content.className = 'viewer-content';
    const heading = tile.querySelector('.card-heading').cloneNode(true);
    heading.querySelector('.expand')?.remove();
    heading.querySelector('h1,h2').id = 'viewer-title';
    content.append(heading);
    if (tile.dataset.role) {
      const role = document.createElement('p');
      role.className = 'project-role-label';
      role.dataset.t = tile.dataset.role;
      role.textContent = translations[tile.dataset.role][language];
      heading.querySelector('h1,h2').after(role);
    }
    const visual = tile.querySelector('summary').querySelector(
      '.tile-preview,.intro-mark,.skill-stack,.contact-mark'
    );
    const gallery = tile.querySelector('.project-device-gallery');
    if (gallery) content.append(gallery.cloneNode(true));
    else if (visual) content.append(visual.cloneNode(true));
    const details = tile.querySelector('.reveal-inner').cloneNode(true);
    details.querySelector('.project-device-gallery')?.remove();
    content.append(details);
    prepared.set(tile, {language, content});
    return content;
  }

  function warm() { tiles.forEach(prepare); }
  if ('requestIdleCallback' in window) requestIdleCallback(warm, {timeout: 1200});
  else setTimeout(warm, 150);
  document.addEventListener('languagechange', () => {
    prepared.clear();
    if (!viewer.open) setTimeout(warm, 0);
  });

  function stopMotion() {
    cancelAnimationFrame(frame1);
    cancelAnimationFrame(frame2);
    animations.forEach(animation => animation.cancel());
    animations = [];
  }

  function cardTransform() {
    const rect = origin.closest('.tile').getBoundingClientRect();
    return 'translate(' + rect.left + 'px,' + rect.top + 'px) scale(' +
      rect.width / viewer.clientWidth + ',' + rect.height / viewer.clientHeight + ')';
  }

  function animate(element, frames, options) {
    const animation = element.animate(frames, {...options, fill: 'forwards'});
    animations.push(animation);
    return animation;
  }

  function closeViewer() {
    if (closing || !viewer.open) return;
    closing = true;
    const current = getComputedStyle(surface).transform;
    stopMotion();
    const finish = () => {
      viewer.close();
      stopMotion();
      viewer.replaceChildren();
      document.body.style.overflow = previousOverflow;
      origin.focus({preventScroll: true});
      closing = false;
    };
    if (reduced.matches) { finish(); return; }
    for (const [selector, duration] of [['.viewer-content', 120], ['.viewer-close', 100]]) {
      const element = viewer.querySelector(selector);
      animate(element, [{opacity: getComputedStyle(element).opacity}, {opacity: 0}], {duration});
    }
    const shrink = animate(surface, [
      {transform: current === 'none' ? 'translate(0,0) scale(1)' : current,
       borderRadius: getComputedStyle(surface).borderRadius},
      {transform: cardTransform(), borderRadius: cardRadius()}
    ], {duration: timing.close, easing});
    shrink.onfinish = finish;
  }

  function openViewer(tile, summary) {
    if (viewer.open) return;
    origin = summary;
    stopMotion();
    viewer.className = 'card-viewer ' + [...tile.classList].filter(name => name !== 'tile').join(' ');
    surface = document.createElement('div');
    surface.className = 'viewer-surface';
    surface.setAttribute('aria-hidden', 'true');
    surface.style.background = getComputedStyle(tile).backgroundColor;
    surface.style.borderRadius = reduced.matches ? '0px' : cardRadius();
    const close = document.createElement('button');
    close.type = 'button';
    close.className = 'viewer-close';
    close.setAttribute('aria-label', closeLabel());
    close.addEventListener('click', closeViewer);
    const content = prepare(tile);
    content.style.opacity = close.style.opacity = reduced.matches ? '1' : '0';
    viewer.replaceChildren(surface, content, close);
    previousOverflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    viewer.showModal();
    surface.style.transform = reduced.matches ? 'none' : cardTransform();
    viewer.scrollTop = 0;
    close.focus({preventScroll: true});
    if (reduced.matches) return;

    // Wait for initial dialog layout before starting the composited transition.
    frame1 = requestAnimationFrame(() => {
      frame2 = requestAnimationFrame(() => {
        if (closing || !viewer.open) return;
        const full = 'translate(0,0) scale(1)';
        const expand = animate(surface, [
          {transform: surface.style.transform, borderRadius: surface.style.borderRadius},
          {transform: full, borderRadius: surface.style.borderRadius, offset: .85},
          {transform: full, borderRadius: '0px'}
        ], {duration: timing.open, easing});
        const reveal = animate(content, [
          {opacity: 0, transform: 'translateY(8px)'},
          {opacity: 1, transform: 'translateY(0)'}
        ], {duration: timing.reveal, delay: 150, easing: 'ease-out'});
        const button = animate(close, [{opacity: 0}, {opacity: 1}], {duration: 160, delay: 290});
        expand.onfinish = () => {
          surface.style.transform = 'none';
          surface.style.borderRadius = '0px';
          expand.cancel();
        };
        reveal.onfinish = () => { content.style.opacity = '1'; reveal.cancel(); };
        button.onfinish = () => { close.style.opacity = '1'; button.cancel(); };
      });
    });
  }

  viewer.addEventListener('cancel', event => {
    event.preventDefault();
    closeViewer();
  });
  tiles.forEach(tile => {
    const summary = tile.querySelector('summary');
    summary.setAttribute('aria-haspopup', 'dialog');
    summary.addEventListener('click', event => {
      event.preventDefault();
      openViewer(tile, summary);
    });
  });
}

